import { test, expect } from '@playwright/test';
import { fileURLToPath } from 'node:url';

const resume = fileURLToPath(new URL('../artifacts/local-setup-resume.pdf', import.meta.url));
const partialResume = fileURLToPath(new URL('../artifacts/local-setup-partial.pdf', import.meta.url));

test('resume-first onboarding extracts editable details, persists review, and recovers from AI failures', async ({ page, request }) => {
  const errors = [], accountCalls = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', req => { if (req.url().includes('/api/v1/')) accountCalls.push(req.url()); });
  await page.goto('/');
  await expect(page).toHaveURL(/#\/onboarding$/);
  await expect(page.getByRole('heading', { name: '01 · Start with your resume' })).toBeVisible();
  await expect(page.getByLabel('Full name *', { exact: true })).toHaveCount(0);
  await page.getByLabel('AI assistant', { exact: true }).selectOption('kiro');
  await page.screenshot({ path: 'artifacts/local-setup-resume-desktop.png', fullPage: true, animations: 'disabled' });
  await page.getByLabel('Upload resume PDF', { exact: true }).setInputFiles(resume);
  await expect(page.getByText('local-setup-resume.pdf', { exact: true })).toBeVisible();
  await page.reload(); // An extraction job belongs to the server, not the browser tab.
  await expect(page.getByText(/could not finish reading it/)).toBeVisible();
  const failed = await (await request.get('/api/local-setup')).json();
  expect(failed.profile).toEqual({});
  expect(failed.profile_draft.email).toBe('candidate@example.com');
  await page.getByRole('button', { name: 'Read resume again', exact: true }).click();
  await expect(page.getByRole('heading', { name: '02 · Review your details' })).toBeVisible();
  await expect(page.getByLabel('Full name *', { exact: true })).toHaveValue('Example Candidate');
  await expect(page.getByLabel('Contact email *', { exact: true })).toHaveValue('candidate@example.com');
  await expect(page.getByLabel('Phone number *', { exact: true })).toHaveValue('+91 5555555555');
  await expect(page.getByLabel('Current city *', { exact: true })).toHaveValue('Pune');
  await expect(page.getByLabel('Skills *', { exact: true })).toHaveValue('Python, SQL, React');
  await expect(page.getByLabel('Experience in years *', { exact: true })).toHaveValue('4');
  await expect(page.getByLabel('Highest qualification', { exact: true })).toHaveValue('BSc Computer Science');
  await expect(page.getByLabel('Current company', { exact: true })).toHaveValue('Example Ltd');
  await expect(page.getByLabel('LinkedIn URL', { exact: true })).toHaveValue('https://linkedin.com/in/example-candidate');
  await page.reload();
  await expect(page.getByLabel('Skills *', { exact: true })).toHaveValue('Python, SQL, React');
  await page.getByLabel('Full name *', { exact: true }).fill('Reviewed Candidate');
  await page.getByLabel('Skills *', { exact: true }).fill('Python, SQL');
  await page.screenshot({ path: 'artifacts/local-setup-profile-desktop.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Confirm details & continue' }).click();
  await expect(page.getByRole('heading', { name: '03 · What would you like next?' })).toBeVisible();
  await expect(page.getByLabel('Target roles *', { exact: true })).toHaveValue('Software Engineer, Backend Engineer');
  await expect(page.getByLabel('Preferred work locations', { exact: true })).toHaveValue('Pune');
  await page.reload();
  await expect(page.getByRole('heading', { name: '03 · What would you like next?' })).toBeVisible();
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  await expect(page.getByLabel('Full name *', { exact: true })).toHaveValue('Reviewed Candidate');
  await page.getByRole('button', { name: 'Confirm details & continue' }).click();
  await page.getByLabel('Target roles *', { exact: true }).fill('Backend Engineer');
  await page.getByLabel('Preferred work locations', { exact: true }).fill('Pune, Remote');
  await page.getByLabel('Preferred work mode', { exact: true }).fill('Remote');
  await page.getByText('Details your resume may not include (optional)', { exact: true }).click();
  await expect(page.getByLabel('Expected annual salary (LPA)', { exact: true })).toHaveValue('');
  await expect(page.getByLabel('Notice period in days', { exact: true })).toHaveValue('');
  await page.screenshot({ path: 'artifacts/local-setup-preferences-desktop.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Save & prepare my answers' }).click();
  await expect(page.getByText(/could not prepare valid answers/)).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: 'Try again', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'You’re ready. Make your next move.' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'You’re ready. Make your next move.' })).toBeVisible();
  const status = await (await request.get('/api/local-setup')).json();
  expect(status.complete).toBe(true);
  expect(status.provider).toBe('kiro');
  expect(status.profile.full_name).toBe('Reviewed Candidate');
  expect(status.profile.skills).toEqual(['Python', 'SQL']);
  expect(status.profile.titles).toEqual(['Backend Engineer']);
  expect(status.profile.preferred_locations).toEqual(['Pune', 'Remote']);
  const answers = await (await request.get('/api/file?name=answers')).json();
  expect(answers.text).toContain('A: Reviewed Candidate');
  expect(answers.text).toContain('A: Backend Engineer');
  await page.getByRole('button', { name: 'Update my details' }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByLabel('Full name *', { exact: true })).toHaveValue('Reviewed Candidate');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'artifacts/local-setup-profile-mobile.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  await page.screenshot({ path: 'artifacts/local-setup-resume-mobile.png', fullPage: true, animations: 'disabled' });
  await page.getByLabel('Replace resume PDF', { exact: true }).setInputFiles(partialResume);
  await expect(page.getByRole('heading', { name: '02 · Review your details' })).toBeVisible();
  await expect(page.getByLabel('Contact email *', { exact: true })).toHaveValue('partial@example.com');
  await expect(page.getByLabel('Full name *', { exact: true })).toHaveValue('');
  await expect(page.getByLabel('Experience in years *', { exact: true })).toHaveValue('');
  await expect(page.getByText('Not found in your resume. Add this to continue.', { exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Confirm details & continue' }).click();
  await expect(page.getByRole('heading', { name: '02 · Review your details' })).toBeVisible();
  const replacement = await (await request.get('/api/local-setup')).json();
  expect(replacement.complete).toBe(false);
  expect(replacement.profile.full_name).toBe('Reviewed Candidate');
  expect(replacement.profile_draft.full_name).toBeUndefined();
  expect(accountCalls).toEqual([]);
  expect(errors).toEqual([]);
});
